using System.Text;
using helengine.baseplatform.Manifest;

namespace helengine.ps3.builder;

/// <summary>
/// Writes the generated scene catalog translation unit that the PlayStation 3 host turns into
/// Core's runtime scene catalog: one array of scene id to cooked relative path pairs, plus the
/// startup scene id. The files land beside generated Core, where the Makefile compiles them as
/// an ordinary generated source.
/// </summary>
public sealed class Ps3StartupManifestWriter {
    /// <summary>Resolves each manifest scene to its cooked artifact and writes the catalog sources.</summary>
    /// <param name="generatedCoreCppRootPath">Generated Core root receiving the catalog sources.</param>
    /// <param name="manifest">Cooked build manifest.</param>
    /// <returns>Path of the written header.</returns>
    public string Write(string generatedCoreCppRootPath, PlatformBuildManifest manifest) {
        if (manifest == null) {
            throw new ArgumentNullException(nameof(manifest));
        }

        PlatformBuildArtifact[] sceneArtifacts = manifest.CookedArtifacts
            .Where(artifact => string.Equals(artifact.ArtifactKind, "scene", StringComparison.OrdinalIgnoreCase))
            .ToArray();

        KeyValuePair<string, string>[] entries = manifest.Scenes.Select(scene => {
            // The manifest links a scene to its cooked artifact by logical id. Older manifests
            // matched on the authored source path instead, so both are tried before giving up.
            PlatformBuildArtifact artifact = sceneArtifacts.FirstOrDefault(
                candidate => string.Equals(candidate.LogicalArtifactId, scene.SceneId, StringComparison.Ordinal));
            if (artifact == null) {
                string normalizedSourceIdentity = Ps3ContentStager.NormalizeRelativePath(scene.SourceIdentity);
                artifact = sceneArtifacts.FirstOrDefault(
                    candidate => string.Equals(Ps3ContentStager.NormalizeRelativePath(candidate.RelativePath), normalizedSourceIdentity, StringComparison.Ordinal));
            }
            if (artifact == null) {
                throw new InvalidOperationException($"PlayStation 3 scene '{scene.SceneId}' has no cooked scene artifact in the manifest.");
            }

            return new KeyValuePair<string, string>(scene.SceneId, artifact.RelativePath);
        }).ToArray();

        return Write(generatedCoreCppRootPath, manifest.StartupSceneId, entries);
    }

    /// <summary>Writes the catalog sources for explicit scene id to cooked path pairs.</summary>
    /// <param name="generatedCoreCppRootPath">Generated Core root receiving the files.</param>
    /// <param name="startupSceneId">Scene the host loads at boot; must be one of the entries.</param>
    /// <param name="entries">Scene id to cooked relative path pairs.</param>
    /// <returns>Path of the written header.</returns>
    public string Write(string generatedCoreCppRootPath, string startupSceneId, IReadOnlyList<KeyValuePair<string, string>> entries) {
        if (string.IsNullOrWhiteSpace(generatedCoreCppRootPath)) {
            throw new ArgumentException("Generated Core root is required.", nameof(generatedCoreCppRootPath));
        } else if (string.IsNullOrWhiteSpace(startupSceneId)) {
            throw new ArgumentException("Startup scene id is required.", nameof(startupSceneId));
        } else if (entries == null || entries.Count == 0) {
            throw new InvalidOperationException("PlayStation 3 startup catalog requires at least one scene.");
        } else if (!entries.Any(entry => string.Equals(entry.Key, startupSceneId, StringComparison.Ordinal))) {
            throw new InvalidOperationException($"PlayStation 3 startup scene '{startupSceneId}' is missing from the catalog.");
        }

        string root = Path.GetFullPath(generatedCoreCppRootPath);
        Directory.CreateDirectory(root);

        StringBuilder header = new();
        header.AppendLine("// Generated by helengine.ps3.builder; do not edit.");
        header.AppendLine("#pragma once");
        header.AppendLine("#include <cstddef>");
        header.AppendLine("struct HEPs3RuntimeSceneCatalogEntry { const char* SceneId; const char* CookedRelativePath; };");
        header.AppendLine("extern \"C\" const char* he_ps3_runtime_startup_scene_id();");
        header.AppendLine("extern \"C\" const HEPs3RuntimeSceneCatalogEntry* he_ps3_runtime_scene_catalog_entries(std::size_t* count);");
        string headerPath = Path.Combine(root, "ps3_runtime_scene_catalog.hpp");
        File.WriteAllText(headerPath, header.ToString(), new UTF8Encoding(false));

        HashSet<string> sceneIds = new(StringComparer.Ordinal);
        StringBuilder source = new();
        source.AppendLine("// Generated by helengine.ps3.builder; do not edit.");
        source.AppendLine("#include \"ps3_runtime_scene_catalog.hpp\"");
        source.AppendLine("namespace {");
        source.AppendLine("const HEPs3RuntimeSceneCatalogEntry kEntries[] = {");
        foreach (KeyValuePair<string, string> entry in entries) {
            if (string.IsNullOrWhiteSpace(entry.Key) || string.IsNullOrWhiteSpace(entry.Value)) {
                throw new InvalidOperationException("PlayStation 3 startup catalog contains an incomplete entry.");
            } else if (!sceneIds.Add(entry.Key)) {
                throw new InvalidOperationException($"PlayStation 3 startup catalog contains duplicate scene id '{entry.Key}'.");
            }

            source.Append("{\"").Append(Escape(entry.Key)).Append("\", \"")
                .Append(Escape(Ps3ContentStager.NormalizeRelativePath(entry.Value))).AppendLine("\"},");
        }
        source.AppendLine("};");
        source.Append("const char kStartupSceneId[] = \"").Append(Escape(startupSceneId)).AppendLine("\";");
        source.AppendLine("}");
        source.AppendLine("extern \"C\" const char* he_ps3_runtime_startup_scene_id() { return kStartupSceneId; }");
        source.AppendLine("extern \"C\" const HEPs3RuntimeSceneCatalogEntry* he_ps3_runtime_scene_catalog_entries(std::size_t* count) { if (count != nullptr) *count = sizeof(kEntries) / sizeof(kEntries[0]); return kEntries; }");
        File.WriteAllText(Path.Combine(root, "ps3_runtime_scene_catalog.cpp"), source.ToString(), new UTF8Encoding(false));

        return headerPath;
    }

    /// <summary>Escapes a value for use inside a C string literal.</summary>
    /// <param name="value">Raw value.</param>
    /// <returns>Escaped value.</returns>
    static string Escape(string value) {
        return value
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal);
    }
}
